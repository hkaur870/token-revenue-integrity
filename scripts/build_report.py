"""Write the monthly revenue integrity report from the dbt output.

Run after `dbt build`:  python scripts/build_report.py
Creates reports/revenue_integrity_report.md (GitHub renders it as a page).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REPORT = ROOT / "reports" / "revenue_integrity_report.md"

CAUSES = {
    "long_context_tier_missed_cache_tokens_excluded": "Haiku 5.5 long-prompt rate missed (cache tokens left out of prompt length)",
    "us_inference_geo_multiplier_missed": "US-only inference billed without the 1.1x multiplier",
    "cache_hits_billed_at_generic_0_1x": "Cache hits on Opus/Sonnet 5.5 billed at 0.1x instead of 0.05x",
    "batch_discount_not_applied_to_cache": "Batch discount not applied to cache tokens",
    "failed_web_searches_billed": "Failed web searches billed",
    "code_execution_free_hours_missed": "1,550 free code-execution hours not applied",
    "late_usage_missed_billing_run": "Late-arriving usage missed the month-end billing run",
    "duplicate_requests_billed": "Metering retries billed twice",
    "partner_month_cutoff_in_pacific_time": "Partner closes the month in Pacific time, not UTC",
    "auto_reload_off_and_requests_not_blocked": "Requests served after prepaid credits ran out",
    "expired_credits_still_spendable": "Credits spent after their one-year expiry",
    "breakage_not_recognized": "Expired credit balance not released to breakage",
    "past_due_collections": "Past-due invoice",
    "awaiting_payment": "Invoice awaiting payment",
    "journal_entry_differs_from_invoice": "GL entry doesn't match the invoice",
    "metering_retries": "Metering retries (de-duplicated by the monitor)",
    "unexplained": "Unexplained: needs investigation",
}


def money(x):
    return "-" if x is None else (f"-${-x:,.2f}" if x < 0 else f"${x:,.2f}")


def build_report(conn):
    q = lambda sql: conn.execute(sql).fetchall()
    cols = ["billing_period", "requests", "total_tokens", "rated_usage_usd", "invoiced_usd", "collected_usd",
            "open_receivables_usd", "deferred_revenue_closing_usd", "breakage_usd", "revenue_leakage_usd",
            "customer_overcharges_usd", "collections_at_risk_usd", "leakage_bps_of_usage",
            "overcharge_bps_of_usage", "exception_count", "total_at_risk_usd"]
    s = dict(zip(cols, q(f"select {', '.join(cols)} from billing_summary")[0]))
    by_cause = q("""select domain, likely_cause, direction, count(*), round(sum(amount_at_risk), 2)
                    from billing_exceptions group by 1, 2, 3 order by 5 desc""")
    levers = q("select lever, revenue_effect_usd, requests_affected from mart_pricing_levers")
    dr = q("""select lot_type, opening_balance, purchases_or_grants, recognized_from_usage, expired_breakage,
                     closing_balance from deferred_revenue_rollforward order by lot_type desc""")
    subs = q("""select plan, monthly_price_usd, subscribers, aggregate_usage_to_price, median_ratio, p95_ratio,
                       pct_above_5x, top_5pct_share_of_usage from mart_subscription_economics
                order by monthly_price_usd""")
    caps = q("select cap_multiple, pct_subscribers_capped, pct_usage_removed from mart_usage_cap_scenarios order by 1")

    out = [
        f"# Revenue Integrity Report: {s['billing_period']}", "",
        "_Synthetic data, priced with Anthropic's public list prices and billing rules. Generated by the pipeline in this repository._", "",
        "## Headline", "",
        f"- **{s['requests']:,} API requests** ({s['total_tokens'] / 1e9:,.1f}B tokens) rated at **{money(s['rated_usage_usd'])}**.",
        f"- **Revenue leakage: {money(s['revenue_leakage_usd'])}** ({s['leakage_bps_of_usage']} bps of usage). "
        f"**Customer overcharges: {money(s['customer_overcharges_usd'])}** ({s['overcharge_bps_of_usage']} bps).",
        f"- **{s['exception_count']} exceptions**, every billing mismatch traced to a specific cause. "
        f"Collections at risk: {money(s['collections_at_risk_usd'])}.",
        f"- Deferred revenue from purchased credits closes at **{money(s['deferred_revenue_closing_usd'])}**; "
        f"breakage recognized: {money(s['breakage_usd'])}.", "",
        "## Dollars at risk by cause", "",
        "| Area | Cause | Direction | Count | Dollars |", "|---|---|---|---|---|",
    ]
    out += [f"| {d} | {CAUSES.get(c, c)} | {dirn} | {n} | {money(a)} |" for d, c, dirn, n, a in by_cause]
    out += ["", "## Pricing levers: revenue effect vs. list price", "",
            "| Lever | Revenue effect | Requests |", "|---|---|---|"]
    out += [f"| {l} | {money(v)} | {n:,} |" for l, v, n in levers]
    out += ["", "## Deferred revenue roll-forward (prepaid credits)", "",
            "| Credit type | Opening | Purchased / granted | Recognized from usage | Expired (breakage) | Closing |",
            "|---|---|---|---|---|---|"]
    out += [f"| {t} | {money(a)} | {money(b)} | {money(c)} | {money(d)} | {money(e)} |" for t, a, b, c, d, e in dr]
    out += ["", "_Included subscriber credits are a memo line: they come with a Claude plan, expire monthly, and are not a separate cash purchase._",
            "", "## Subscription economics (illustrative)", "",
            "| Plan | Price | Subscribers | Usage ÷ price (all) | Median | P95 | > 5x price | Top 5% share of usage |",
            "|---|---|---|---|---|---|---|---|"]
    out += [f"| {p} | {money(pr)} | {n:,} | {a}x | {m}x | {p95}x | {gt5}% | {top}% |"
            for p, pr, n, a, m, p95, gt5, top in subs]
    out += ["", "| Usage cap (x plan price) | Subscribers affected | Usage removed |", "|---|---|---|"]
    out += [f"| {c}x | {p}% | {u}% |" for c, p, u in caps]
    out.append("")
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text("\n".join(out))
    return s["exception_count"]


if __name__ == "__main__":
    import duckdb
    conn = duckdb.connect(str(ROOT / "token_revenue.duckdb"), read_only=True)
    print(f"Wrote {REPORT} ({build_report(conn)} exceptions)")
